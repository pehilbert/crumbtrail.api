import { Prop, Schema, SchemaFactory } from '@nestjs/mongoose';
import { randomUUID } from 'node:crypto';

@Schema({ _id: false, versionKey: false })
export class Ingredient {
  /** Null for things like "salt, to taste". */
  @Prop({ type: Number, default: null })
  quantity: number | null;

  @Prop({ type: String, default: null })
  unit: string | null;

  @Prop({ type: String, required: true })
  ingredient: string;

  @Prop({ type: String, default: null })
  adjective: string | null;
}

const IngredientSchema = SchemaFactory.createForClass(Ingredient);

@Schema({
  collection: 'recipes',
  timestamps: { createdAt: 'publishedAt', updatedAt: false },
  versionKey: false,
})
export class Recipe {
  /** GUID string, generated by the API (not a Mongo ObjectId). */
  @Prop({ type: String, default: () => randomUUID() })
  _id: string;

  /** User.ID of the author. Set from the auth token and never changed. */
  @Prop({ type: String, required: true })
  authorId: string;

  @Prop({ type: String, required: true })
  title: string;

  @Prop({ type: String, default: null })
  description: string | null;

  @Prop({ type: [String], default: [] })
  tags: string[];

  @Prop({ type: Number, default: null })
  timeEstimateMinutes: number | null;

  @Prop({ type: [IngredientSchema], default: [] })
  ingredients: Ingredient[];

  @Prop({ type: [String], default: [] })
  steps: string[];

  /** Null until the first edit. Journal changes don't count as edits. */
  @Prop({ type: Date, default: null })
  editedAt: Date | null;

  /** Soft delete. Archived recipes are treated as missing everywhere. */
  @Prop({ type: Boolean, required: true, default: false })
  archived: boolean;

  /** Set by Mongoose timestamps. */
  publishedAt: Date;
}

export const RecipeSchema = SchemaFactory.createForClass(Recipe);

// Serves GET /recipes/me: an author's live recipes, newest first.
RecipeSchema.index({ authorId: 1, archived: 1, publishedAt: -1 });
